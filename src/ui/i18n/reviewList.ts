import type { Dictionary, HiDictionary, ReviewEntry } from '../types.ts';

/** One entry for each Hindi key whose reviewed flag is not true (R12.9, R12.10). */
export function reviewList(hi: HiDictionary, en: Dictionary): ReviewEntry[] {
  return Object.keys(hi)
    .filter((key) => hi[key]?.reviewed !== true)
    .map((key) => ({ key, hi: hi[key]?.text ?? '', en: Object.hasOwn(en, key) ? (en[key] as string) : '' }));
}

function cell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

/** The text of docs/HINDI_REVIEW.md for a review list (R12.12). */
export function renderReviewMarkdown(entries: readonly ReviewEntry[]): string {
  const lines = [
    '# Hindi review list',
    '',
    'Generated by `npm run review-list` from `src/ui/i18n/hi.json`. Do not edit by hand.',
    'To mark a string as reviewed, set its `reviewed` flag to `true` in `hi.json` and run the script again.',
    '',
    `Unreviewed strings: ${entries.length}`,
    '',
  ];
  if (entries.length > 0) {
    lines.push('| Key | Hindi | English |', '| --- | --- | --- |');
    for (const entry of entries) lines.push(`| \`${cell(entry.key)}\` | ${cell(entry.hi)} | ${cell(entry.en)} |`);
    lines.push('');
  }
  return lines.join('\n');
}
